#!/usr/bin/env bash
# Publish the demo cluster's ingress controller on the Mac's 127.0.0.1:80.
#
# OrbStack has no cloud provider, so Ingress objects get no address and NodePorts are not reachable
# from the host. macOS also needs root to bind port 80, which this demo does not assume. OrbStack's
# Docker can publish port 80 without root, so this script runs a tiny nginx front door that keeps
# the Host header and proxies to the in-cluster ingress-nginx controller Service.
#
# Usage:
#   ./scripts/ingress-frontdoor.sh start [port]   # default port 80
#   ./scripts/ingress-frontdoor.sh stop
#   ./scripts/ingress-frontdoor.sh status [port]
#
# The controller itself is installed from k8s_control_plane/deploy/ingress-nginx.yaml:
#   kubectl apply -f k8s_control_plane/deploy/ingress-nginx.yaml
set -euo pipefail

NAME="match-ingress-frontdoor"
NAMESPACE="${INGRESS_NAMESPACE:-ingress-nginx}"
SERVICE="${INGRESS_SERVICE:-ingress-nginx-controller}"
DEPLOYMENT="${INGRESS_DEPLOYMENT:-ingress-nginx-controller}"
CONFIG_DIR="${TMPDIR:-/tmp}/matchengine-ingress-frontdoor"
CONFIG_FILE="$CONFIG_DIR/default.conf"
IMAGE="${INGRESS_FRONTDOOR_IMAGE:-nginx:alpine}"

usage() {
  sed -n '2,16p' "$0" | sed 's/^# \{0,1\}//'
  exit 1
}

require_kubectl() {
  command -v kubectl >/dev/null 2>&1 || {
    echo "kubectl is not on PATH" >&2
    exit 1
  }
  kubectl -n "$NAMESPACE" get "deployment/$DEPLOYMENT" >/dev/null 2>&1 || {
    echo "ingress-nginx is not installed; run:" >&2
    echo "  kubectl apply -f k8s_control_plane/deploy/ingress-nginx.yaml" >&2
    exit 1
  }
}

controller_ip() {
  local ip
  ip="$(kubectl -n "$NAMESPACE" get "service/$SERVICE" -o jsonpath='{.spec.clusterIP}')"
  if [[ -z "$ip" || "$ip" == "None" ]]; then
    echo "service $NAMESPACE/$SERVICE has no ClusterIP" >&2
    exit 1
  fi
  printf '%s' "$ip"
}

write_config() {
  local ip="$1"
  mkdir -p "$CONFIG_DIR"
  cat >"$CONFIG_FILE" <<EOF
# Generated by scripts/ingress-frontdoor.sh; targets $NAMESPACE/$SERVICE at $ip.
map \$http_upgrade \$connection_upgrade {
    default upgrade;
    ''      close;
}

server {
    listen 80 default_server;
    server_name _;

    # WebSocket streams (market-data terminal) stay open for the session.
    proxy_http_version 1.1;
    proxy_set_header Upgrade \$http_upgrade;
    proxy_set_header Connection \$connection_upgrade;
    proxy_set_header Host \$host;
    proxy_set_header X-Real-IP \$remote_addr;
    proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
    proxy_set_header X-Forwarded-Proto \$scheme;
    proxy_read_timeout 3600s;
    proxy_send_timeout 3600s;
    proxy_buffering off;

    location / {
        proxy_pass http://$ip:80;
    }
}
EOF
}

start() {
  local port="${1:-80}"
  require_kubectl
  # The rendered market-data and engine NetworkPolicies admit the gateway role. Label the
  # controller namespace so the ingress controller can reach the feed/console ports.
  kubectl label namespace "$NAMESPACE" matching.io/role=gateway --overwrite >/dev/null
  kubectl -n "$NAMESPACE" rollout status "deployment/$DEPLOYMENT" --timeout=180s >/dev/null
  local ip
  ip="$(controller_ip)"
  write_config "$ip"
  docker rm -f "$NAME" >/dev/null 2>&1 || true
  docker run -d \
    --name "$NAME" \
    --restart unless-stopped \
    -p "${port}:80" \
    -v "$CONFIG_FILE:/etc/nginx/conf.d/default.conf:ro" \
    "$IMAGE" >/dev/null
  sleep 1
  echo "front door: http://127.0.0.1:${port}/ -> ${NAMESPACE}/${SERVICE} (${ip}:80)"
  echo "try: curl -s -o /dev/null -w '%{http_code}\\n' -H 'Host: users-0.orders.match-eu-1.example' http://127.0.0.1:${port}/demo/"
}

stop() {
  docker rm -f "$NAME" >/dev/null 2>&1 || true
  echo "stopped $NAME"
}

status() {
  local port="${1:-80}"
  if docker inspect "$NAME" >/dev/null 2>&1; then
    docker inspect "$NAME" --format 'container {{.Name}} {{.State.Status}} ports={{json .NetworkSettings.Ports}}'
  else
    echo "container $NAME is not running"
  fi
  if curl -s -o /dev/null --max-time 3 "http://127.0.0.1:${port}/"; then
    echo "127.0.0.1:${port} is listening"
  else
    echo "127.0.0.1:${port} is not reachable"
  fi
}

command="${1:-}"
case "$command" in
  start) shift; start "${1:-80}" ;;
  stop) stop ;;
  status) shift; status "${1:-80}" ;;
  *) usage ;;
esac
